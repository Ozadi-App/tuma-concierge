#!/usr/bin/env node
// Generates the tiny placeholder lesson videos used by the Peebee Learn demo content and
// writes them to apps/api/src/education/demo-media.ts as base64, so the API can seed them
// into R2 without any file hosting. Needs ffmpeg with the drawtext filter and an Inter/TTF font.
//
//   node scripts/gen-demo-videos.mjs [path/to/font.otf]
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const font = process.argv[2] ?? "/usr/share/fonts/opentype/inter/InterDisplay-Bold.otf";
const SECONDS = 12;
const VARIANTS = [
  { key: "sprouts", label: "SPROUTS" },
  { key: "foundations", label: "FOUNDATIONS" },
  { key: "academy", label: "ACADEMY" },
  { key: "compass", label: "COMPASS" },
  { key: "skills", label: "SKILLS" },
  { key: "live", label: "LIVE CLASS" },
];

const dir = mkdtempSync(join(tmpdir(), "peebee-demo-video-"));
const out = {};
for (const v of VARIANTS) {
  const file = join(dir, `${v.key}.mp4`);
  const text = (t, size, color, y) => `drawtext=fontfile=${font}:text='${t}':fontcolor=${color}:fontsize=${size}:x=(w-text_w)/2:y=${y}`;
  const filter = [
    "drawbox=x=0:y=0:w=480:h=8:color=0xc9a227@1:t=fill",
    text(v.label, 22, "0xc9a227", 64),
    text("Placeholder lesson video", 30, "white", 108),
    text("Peebee Learn demo", 18, "0xb8b0a0", 156),
    `drawtext=fontfile=${font}:text='%{eif\\:t\\:d}s':fontcolor=0xb8b0a0:fontsize=18:x=(w-text_w)/2:y=192`,
    `drawbox=x=40:y=232:w='t*${Math.floor(400 / SECONDS)}':h=6:color=0xc9a227@1:t=fill`,
  ].join(",");
  execFileSync(
    "ffmpeg",
    ["-y", "-hide_banner", "-loglevel", "error", "-f", "lavfi", "-i", `color=c=0x14110a:s=480x270:r=15:d=${SECONDS}`, "-vf", filter, "-c:v", "libx264", "-preset", "veryslow", "-crf", "36", "-pix_fmt", "yuv420p", "-movflags", "+faststart", "-an", file],
    { stdio: "inherit" },
  );
  out[v.key] = readFileSync(file).toString("base64");
}

const body = `// Generated by scripts/gen-demo-videos.mjs. Do not edit by hand.
// Tiny ${SECONDS}-second placeholder lesson videos (480x270, H.264, no audio) used by the demo content.

export const DEMO_VIDEO_SECONDS = ${SECONDS};

const DEMO_VIDEOS_BASE64: Record<string, string> = {
${Object.entries(out).map(([k, b]) => `  ${k}: "${b}",`).join("\n")}
};

export type DemoVideoKey = ${VARIANTS.map((v) => `"${v.key}"`).join(" | ")};

/** The MP4 bytes for a placeholder video. */
export function demoVideoBytes(key: DemoVideoKey): Uint8Array {
  const raw = atob(DEMO_VIDEOS_BASE64[key]);
  const bytes = new Uint8Array(raw.length);
  for (let i = 0; i < raw.length; i += 1) bytes[i] = raw.charCodeAt(i);
  return bytes;
}
`;
writeFileSync(new URL("../apps/api/src/education/demo-media.ts", import.meta.url), body);
console.log("wrote demo-media.ts", Object.fromEntries(Object.entries(out).map(([k, b]) => [k, Math.round((b.length * 3) / 4)])));
